export interface ReportFigure { svg: string | null; label: string }

export function htmlReport({ title, kicker, md, figures = [], generatedAt }: { title: string; kicker: string; md: string; figures?: ReportFigure[]; generatedAt: string }): string {
  const pics = figures
    .filter((f): f is { svg: string; label: string } => isSafeSvg(f.svg))
    .map((f) => `<figure class="fig" role="img" aria-label="${escapeHtml(f.label)}">${f.svg.trim()}<p>${escapeHtml(f.label)}</p></figure>`);
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="generator" content="${APP_NAME}">
<title>${escapeHtml(title)}</title>
<style>${CSS}</style>
</head>
<body>
<main>
<article class="sheet">
<p class="eyebrow">${escapeHtml(kicker)}</p>
${markdownToHtml(md)}
${pics.join('\n')}
</article>
<p class="meta">Generated by ${APP_NAME} on ${escapeHtml(generatedAt.slice(0, 10))}. No external resources are loaded.</p>
</main>
</body>
</html>
`;
}

/** A file name from an artefact's title, or from a fallback when the title has no letters or digits. */
export const fileStem = (title: string, fallback: string): string => (/[a-z0-9]/i.test(title.normalize('NFKD')) ? slugify(title) : slugify(fallback));

/** A heading line from user text: one line, no leading `#`. */
export const headingText = (s: string, fallback: string): string => s.replace(/\s*\r?\n\s*/g, ' ').trim().replace(/^#+\s*/, '') || fallback;
